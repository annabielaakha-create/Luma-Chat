import test from 'node:test';
import assert from 'node:assert/strict';
import { generatePdfBlob } from './pdfGenerator.js';

test('generatePdfBlob generates a valid binary PDF blob with application/pdf MIME type', async () => {
  const title = 'Quarterly Strategy Report';
  const content = `
# Executive Summary
This is the quarterly strategy report generated by LUMA AI.

## Key Performance Indicators
- **Revenue**: $1.2M (+14% YoY)
- **Active Users**: 45,000 monthly active users
- **Latency**: 140ms average response time

## Strategic Roadmap
1. Enhance multi-format artifact rendering.
2. Expand document processing pipeline.
3. Streamline Cloud Run startup.
`;

  const blob = generatePdfBlob(title, content);

  assert.equal(blob instanceof Blob, true);
  assert.equal(blob.type, 'application/pdf');
  assert.equal(blob.size > 1000, true);

  const arrayBuffer = await blob.arrayBuffer();
  const uint8 = new Uint8Array(arrayBuffer);
  const header = String.fromCharCode(...uint8.slice(0, 5));
  assert.equal(header, '%PDF-');
});
